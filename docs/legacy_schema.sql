CREATE FUNCTION GET_PUR_RATE (pCMP_ID NUMBER,pICODE VARCHAR2,pTRNDATE DATE) RETURN NUMBER IS
v_RATE NUMBER;
BEGIN
  SELECT RATE  INTO v_RATE
  FROM
  (SELECT OP.CMP_ID,OP.OPEN_DATE TRNDATE,OP.TRNID VNO,OP.ICODE,NVL(OP.OPEN_RATE,0) RATE
  FROM  OPEN_STOCK OP,PUR_ITEM I
  WHERE OP.ICODE      = I.ICODE
  AND   OP.CMP_ID     = pCMP_ID
  AND   OP.OPEN_DATE <= pTRNDATE
  AND   OP.ICODE      = pICODE
  UNION ALL
  SELECT PM.CMP_ID,PM.TRNDATE,PD.VNO,PD.ICODE,NVL(PD.RATE,0)RATE
  FROM  PMST PM , PDTL PD, PUR_ITEM I
  WHERE PM.TRNID = PD.TRNID
  AND   PD.ICODE    = I.ICODE
  AND   PM.TRN_TYPE = 7
  AND   PM.CMP_ID   = pCMP_ID
  AND   PM.TRNDATE <= pTRNDATE
  AND   PD.ICODE    = pICODE
  ) A
  WHERE A.VNO =
  (
  SELECT MAX(B.VNO)
  FROM
  (SELECT OP.CMP_ID,OP.OPEN_DATE TRNDATE,OP.TRNID VNO,OP.ICODE
  FROM  OPEN_STOCK OP
  WHERE OP.CMP_ID     = pCMP_ID
  AND   OP.OPEN_DATE <= pTRNDATE
  AND   OP.ICODE      = pICODE
  UNION ALL
  SELECT PM.CMP_ID,PM.TRNDATE,PD.VNO,PD.ICODE
  FROM  PMST PM , PDTL PD
  WHERE PM.TRNID    = PD.TRNID
  AND   PM.TRN_TYPE = 7
  AND   PM.CMP_ID   = pCMP_ID
  AND   PM.TRNDATE <= pTRNDATE
  AND   PD.ICODE    = pICODE
  )B
  );
   RETURN v_RATE;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
  BEGIN
   SELECT RATE  INTO v_RATE
   FROM
   (
   SELECT PM.CMP_ID,PM.TRNDATE,PD.VNO,PD.ICODE,NVL(PD.RATE,0) RATE
   FROM  PMST PM , PDTL PD
   WHERE PM.TRNID    = PD.TRNID
   AND   PM.TRN_TYPE = 10
   AND   PM.CMP_ID   = pCMP_ID
   AND   PM.TRNDATE <= pTRNDATE
   AND   PD.ICODE    = pICODE
  ) A
  WHERE A.VNO =
  (
  SELECT MAX(B.VNO)
  FROM
  (
  SELECT PM.CMP_ID,PM.TRNDATE,PD.VNO
  FROM  PMST PM , PDTL PD
  WHERE PM.TRNID    = PD.TRNID
  AND   PM.TRN_TYPE = 10
  AND   PM.CMP_ID   = pCMP_ID
  AND   PM.TRNDATE <= pTRNDATE
  AND   PD.ICODE    = pICODE
  )B
  );
   RETURN v_RATE;
 EXCEPTION
  WHEN NO_DATA_FOUND THEN
  RETURN 0;
 END;
END;
